"""Builds the text preview page: template.html plus the font data and glyph code, into index.html.

Run from anywhere:

    python site/text-preview/build.py          # write index.html
    python site/text-preview/build.py --check  # fail if index.html is out of date

faces.json is generated by tools/fontgen.py (the baked bitmap faces); glyphs.js is the
DOM-free segment-face drawing code. Both are inlined so the page works as a single file.
"""

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent


def build():
    faces = (HERE / "faces.json").read_text(encoding="utf-8").strip()
    glyphs = (HERE / "glyphs.js").read_text(encoding="utf-8")
    data = f"const FACES_DATA = {faces};\n\n" + glyphs
    template = (HERE / "template.html").read_text(encoding="utf-8")
    return template.replace("/*FONTS*/", data)


def main():
    page = build()
    out = HERE / "index.html"
    if "--check" in sys.argv:
        if not out.exists() or out.read_text(encoding="utf-8") != page:
            sys.exit("site/text-preview/index.html is out of date: run python site/text-preview/build.py")
        print("index.html is up to date")
    else:
        out.write_text(page, encoding="utf-8", newline="\n")
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
